"""Single source of truth for this local fork's version.

Bump ``APP_VERSION`` here when releasing a build (new features -> minor bump,
bug fixes -> patch bump).  ``build_local.py`` reads it to name the EXE and to
generate the Windows VERSIONINFO resource, so nothing else needs editing.
"""
import re

APP_VERSION = '0.13.1-Beta'
APP_NAME = 'NotabilityEditor'

# Numeric counterpart used by the Windows VERSIONINFO resource.  The last
# field stays 65535 to match the original Beta builds.
_MATCH = re.fullmatch(r'(\d+)\.(\d+)\.(\d+)(?:-[A-Za-z]+)?', APP_VERSION)
if _MATCH is None:
    raise ValueError('APP_VERSION must look like 0.10.1-Beta')
VERSION_NUMBERS = tuple(int(part) for part in _MATCH.groups()) + (65535,)


def release_track(version=None):
    """Major release track = the first numeric field (0 for 0.13.1-Beta).

    Startup notices are keyed to this track: 0.13.0 -> 0.13.1 -> 0.14.0 all
    belong to track 0, so only a 0.x -> 1.x style change re-prompts.
    """
    value = str(version or APP_VERSION).split('-', 1)[0]
    parts = value.split('.')
    if len(parts) != 3 or not parts[0].isdigit():
        raise ValueError('无法识别应用版本号：' + str(version))
    return int(parts[0])


def exe_basename():
    """e.g. NotabilityEditor-0.13.0-Beta-local (without .exe)."""
    return f'{APP_NAME}-{APP_VERSION}-local'


def version_info_text():
    """Contents of the PyInstaller --version-file resource."""
    numbers = ', '.join(str(value) for value in VERSION_NUMBERS)
    return f'''# Generated by build_local.py from core.ne_app_version. Do not edit by hand.
# PyInstaller Windows VERSIONINFO resource for {APP_NAME} {APP_VERSION}.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({numbers}),
    prodvers=({numbers}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904b0', [
        StringStruct('CompanyName', '{APP_NAME}'),
        StringStruct('FileDescription', '{APP_NAME} - local NTB note viewer and editor'),
        StringStruct('FileVersion', '{APP_VERSION}'),
        StringStruct('InternalName', '{APP_NAME}'),
        StringStruct('OriginalFilename', '{APP_NAME}.exe'),
        StringStruct('ProductName', '{APP_NAME}'),
        StringStruct('ProductVersion', '{APP_VERSION}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
'''
